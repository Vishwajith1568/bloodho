const DICTS: Record<Lang, Dict> = { en, hi, te };

const LangCtx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, fallback?: string) => string;
}>(null as any);

export function LangProvider({ children }: { children: any }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('bf_lang') as Lang | null;
    return saved && DICTS[saved] ? saved : 'en';
  });

  useEffect(() => {
    localStorage.setItem('bf_lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  /** Falls back to English, then to the supplied fallback, then to the key. */
  const t = (key: string, fallback?: string) =>
    DICTS[lang][key] ?? en[key] ?? fallback ?? key;

  return (
    <LangCtx.Provider value={{ lang, setLang: setLangState, t }}>
      {children}
    </LangCtx.Provider>
  );
}

export const useT = () => useContext(LangCtx);
